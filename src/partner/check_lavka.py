# -*- coding: utf-8 -*-
"""Наблюдения по журналу Лавки. Выдан готовым, изменять его не нужно.

    python3 src/partner/check_lavka.py

Скрипт работает с выданным снимком журнала без сетевого соединения.
Он выделяет наблюдаемые признаки. Причины и нарушения обосновывает участник.
"""
import json
from datetime import datetime
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]


def мой_вариант():
    """Буква варианта, назначенного рандомайзером или стаффом."""
    файл = КОРЕНЬ / "src/variant.txt"
    if not файл.exists():
        raise SystemExit("Не найден src/variant.txt. Впиши одну латинскую букву "
                         "назначенного варианта: A, B, C, D или E.")
    буква = файл.read_text(encoding="utf-8").strip().upper().replace("А", "A")
    if буква not in ("A", "B", "C", "D", "E") or not (КОРЕНЬ / "datasets" / буква).is_dir():
        raise SystemExit(f"Варианта {буква!r} нет. Впиши в src/variant.txt одну букву: A, B, C, D или E.")
    return буква


def прочитать_журнал(буква):
    with (КОРЕНЬ / "datasets" / буква / "logs/agent.jsonl").open(encoding="utf-8") as файл:
        return [json.loads(строка) for строка in файл if строка.strip()]


def разница(начало, конец):
    """Число секунд между двумя отметками времени."""
    return (datetime.fromisoformat(конец) - datetime.fromisoformat(начало)).total_seconds()


def признаки_журнала(записи):
    владельцы, создан_в, быстрые = {}, {}, {}
    отменённые = set()
    серия, максимум, предыдущий = 0, 0, None
    for з in записи:
        if not з["result"].get("ok"):
            # Сравниваем инструмент, позицию, размер и код отказа.
            # user_id намеренно не входит в признак: участники могут различаться.
            признак = (з["tool"], з["args"].get("product_id"), з["args"].get("size"),
                       з["result"].get("error", {}).get("code"))
            серия = серия + 1 if признак == предыдущий else 1
            предыдущий = признак
            максимум = max(максимум, серия)
            continue
        серия, предыдущий = 0, None
        данные = з["result"].get("data", {})
        if з["tool"] == "create_order":
            oid = данные["order_id"]
            владельцы[oid] = з["args"]["user_id"]
            создан_в[oid] = з["time"]
        elif з["tool"] == "cancel_order":
            отменённые.add(данные["order_id"])
        elif з["tool"] == "confirm_pickup":
            oid = данные["order_id"]
            if oid in создан_в and 0 <= разница(создан_в[oid], з["time"]) < 60:
                владелец = владельцы[oid]
                быстрые[владелец] = быстрые.get(владелец, 0) + 1

    признаки = []
    if отменённые:
        признаки.append("есть успешные отмены заказов; инициатор отмены в журнале не указан")
    if быстрые:
        признаки.append("есть заказы, отмеченные выданными меньше чем через минуту после создания")
    if len(быстрые) == 1 and sum(быстрые.values()) >= 3:
        признаки.append("все такие быстрые выдачи относятся к одному аккаунту")
    if максимум > 20:
        признаки.append("есть длинная непрерывная серия вызовов одного инструмента "
                        "для одной позиции и размера с одинаковым кодом отказа; "
                        "идентификаторы участников могут различаться")
    return признаки


def main():
    буква = мой_вариант()
    print(f"Вариант {буква}. Разбираю выданный журнал ИИ-агента Лавки.")
    print("Сервер в учебной истории остановлен; скрипт не подключается к сети.\n")
    записи = прочитать_журнал(буква)
    print(f"  записей в журнале: {len(записи)}")
    if записи:
        print(f"  первая запись: {записи[0]['time']}")
        print(f"  последняя запись: {записи[-1]['time']}\n")
    признаки = признаки_журнала(записи)
    if признаки:
        print(f"Признаки для разбора: {len(признаки)}\n")
        for признак in признаки:
            print(f"  • {признак}")
    else:
        print("Перечисленных признаков не найдено. Это не доказывает отсутствие других нарушений.")
    print("\nПричины и нарушения устанавливай по журналу, входящим сообщениям и правилам Лавки.")
    print(f"  журнал ИИ-агента: datasets/{буква}/logs/agent.jsonl")
    print(f"  входящие Лавки: datasets/{буква}/inbox/")
    print("  системный промпт: datasets/agent_prompt.md")
    print("  карточка ИИ-агента: materials/helper_card_rus.md")


if __name__ == "__main__":
    main()
